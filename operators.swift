**1. Arithmetic operators**



let a: Int = 35

let b: Int = 8

print("Sum:", a + b)

print("Difference:", a - b)

print("Product:", a \* b)

print("Division:", a / b)

print("Remainder:", a % b)





**2. Comparison operators**



let a = 60

let b = 60

print("a is greater:", a > b)

print("Both marks are equal:", a == b)

print("First mark is smaller:", a < b)





**3. Logical operator**



let age = 17

let hasID = true

let eligible = age >= 18 \&\& hasID

print("Eligible:", eligible)



**4. Ternary operator**



let mark=30

let result=mark>=35?"Pass":"Fail"

print("Result:",result)





**5. Type conversion — Int and Double**





let wholeNumber:Int = 15

let decimalNumber:Double = 4.7

let result = Double(wholeNumber)+decimalNumber

